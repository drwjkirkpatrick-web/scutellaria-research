#!/usr/bin/env python3
"""Generate paper/sources_block.tex mechanically from the citation ledger.

Cited ids come from \\src{n} macros in the .tex (single regex), never from
memory. Each entry prints ledger URL + captured verbatim evidence quotes.
Bibliographic decoration (authors/year/journal/doi) comes from
research/master_map.json, which merge_and_register.py builds from the
children's fetched metadata.
"""
import json
import re
import sys
from pathlib import Path

PROJ = Path("/home/walker/projects/scutellaria-research")
LEDGER = PROJ / "citations" / "ledger.json"
TEX = PROJ / "paper" / "scutellaria_review.tex"
OUT = PROJ / "paper" / "sources_block.tex"
MASTER = PROJ / "research" / "master_map.json"

MD_LINK_RE = re.compile(r"\[([^\]]*)\]\((?:[^()\s]|\([^()]*\))*\)")
MD_NOISE_RE = re.compile(r"[*`]+")


def tex_escape(s: str) -> str:
    s = s or ""
    s = s.replace("\\", "\\textbackslash{}")
    s = s.replace("{", "\\{").replace("}", "\\}")
    s = s.replace("&", "\\&").replace("%", "\\%").replace("$", "\\$").replace("#", "\\#")
    s = s.replace("_", "\\_").replace("~", "\\textasciitilde{}").replace("^", "\\textasciicircum{}")
    return s


def clean_quote(q: str) -> str:
    q = MD_LINK_RE.sub(r"\1", q or "")
    q = MD_NOISE_RE.sub("", q)
    q = " ".join(q.split())
    return q


def fmt_authors(a: str) -> str:
    return tex_escape(a) if a else ""


def fmt_year(y) -> str:
    if y in (None, "", 0):
        return ""
    return f" ({int(y) if isinstance(y, (int, float)) else tex_escape(str(y))})"


def main():
    tex_files = sorted(p for p in (PROJ / "paper").glob("*.tex") if p.name != OUT.name)
    tex = "\n".join(p.read_text(encoding="utf-8") for p in tex_files)
    cited = sorted({int(n) for n in re.findall(r"\\src\{(\d+)\}", tex)})
    if not cited:
        sys.exit("no \\src{} ids found in the .tex yet")

    ledger = json.loads(LEDGER.read_text(encoding="utf-8"))
    by_id = {s["id"]: s for s in ledger["sources"]}

    meta_by_url = {}
    if MASTER.exists():
        mm = json.loads(MASTER.read_text(encoding="utf-8"))
        meta_by_url = {v["url"]: v for v in mm.values()}

    missing = [i for i in cited if i not in by_id]
    if missing:
        sys.exit(f"cited ids not in ledger (hallucinated?): {missing}")

    lines = []
    quoted_n = 0
    for i in cited:
        e = by_id[i]
        meta = meta_by_url.get(e["url"], {})
        parts = [f"[{i}]"]
        authors = fmt_authors(meta.get("authors", ""))
        if authors:
            parts.append(f"{authors}{fmt_year(meta.get('year'))}.")
        title = tex_escape(meta.get("title") or e.get("title") or "")
        if title:
            parts.append(f"{title}.")
        jr = tex_escape(meta.get("journal_or_publisher", ""))
        vp = tex_escape(meta.get("vol_pages", ""))
        if jr:
            parts.append(f"\\textit{{{jr}}}" + (f" {vp}." if vp else "."))
        if meta.get("doi"):
            parts.append(f"\\href{{https://doi.org/{tex_escape(str(meta['doi']))}}}{{doi:{tex_escape(str(meta['doi']))}}}.")
        elif meta.get("pmid"):
            parts.append(f"\\href{{https://pubmed.ncbi.nlm.nih.gov/{int(meta['pmid'])}/}}{{PMID:{int(meta['pmid'])}}}.")
        parts.append(f"\\url{{{e['url']}}} (accessed {e.get('accessed', '')}).")

        lines.append("\\noindent " + " ".join(parts))

        quotes = [clean_quote(q.get("text", "")) for q in (e.get("quotes") or [])]
        quotes = [q for q in quotes if len(q.split()) >= 3][:3]
        if quotes:
            quoted_n += 1
            for q in quotes:
                lines.append(f"\\noindent\\hspace*{{2em}}\\small\\textit{{Evidence:}} ``{tex_escape(q)}''")

    header = (
        f"% GENERATED by scripts/gen_sources_block.py -- do not edit by hand.\n"
        f"% {len(cited)} cited sources; {quoted_n} carry captured verbatim quotes;\n"
        f"% sources without quotes were registered from retrieved pages whose text\n"
        f"% did not yield a clean quotable sentence -- cite them from the fetched page.\n"
    )
    OUT.write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}: {len(cited)} sources, {quoted_n} with evidence quotes")


if __name__ == "__main__":
    main()